%% ЛР: Интенсивность ошибки передачи сигнала (variant 66)
clear; clc;  % очистка рабочей области и командного окна

%% Базовые параметры моделирования (0..10 c)
Ts = 0.001;              % шаг дискретизации, c
Ns = 10000;              % число отсчётов (Ts * Ns = 10 c моделирования)

% Константы по варианту 66 (из таблицы)
fc  = 700;               % несущая частота, Гц
Am  = 201;               % амплитуда / девиация частоты (K1 = A = 201)
R   = 42;                % параметр канала (расстояние / сопротивление)

% Факторы: mr и NP (Ф1 и Ф2)
mr_min = 2.52;           % Ф1 min – минимальное значение mr
mr_max = 10;             % Ф1 max – максимальное значение mr
NP_min = 0.01;           % Ф2 min – минимальная мощность шума NP
NP_max = 1.01;           % Ф2 max – максимальная мощность шума NP

%% Факторы эксперимента: mr и NP
nf   = 2;                        % число факторов
minf = [mr_min NP_min];          % [mr_min, NP_min]
maxf = [mr_max NP_max];          % [mr_max, NP_max]

% Построение факторного плана 2^2 (как у друга)
fracplan = fracfact('a b ab');   % план в кодированных переменных (-1, +1)
N        = 2^nf;                 % 2^2 = 4 эксперимента
fictfact = ones(N,1);            % фиктивная переменная для свободного члена
X        = [fictfact fracplan];  % матрица плана с фиктивной переменной

% Натуральные значения факторов [mr, NP]
fraceks = zeros(N, nf);
for i = 1:nf
    for j = 1:N
        % переход из кода (-1,+1) в натуральные значения
        fraceks(j,i) = minf(i) + (fracplan(j,i)+1)*(maxf(i)-minf(i))/2;
    end
end

disp('План в натуральных единицах [mr, NP]:');
disp(fraceks);

%% Тактическое планирование точности для оценки интенсивности ошибки
d_sigma   = 0.75;                 % относительная погрешность оценки дисперсии
alpha     = 0.02;                 % уровень значимости
tkr_alpha = norminv(1 - alpha/2); % квантиль нормального распределения
NE        = round(1 + 2*tkr_alpha^2/d_sigma^2);  % число испытаний
fprintf('Расчетное число испытаний NE = %d\n', NE);

%% Основной цикл по точкам плана: λ_err = f(mr, NP)
Y = zeros(N,1);   % вектор реакций (интенсивность ошибки передачи сигнала)

for j = 1:N
    % Текущие значения факторов
    mr = fraceks(j,1);   % коэффициент модуляции (Ф1)
    NP = fraceks(j,2);   % мощность шума (Ф2)

    uo = zeros(NE,1);    % переданные биты (0/1)
    u1 = zeros(NE,1);    % принятые биты (0/1)

    for k = 1:NE
        to = round(rand*100);  % seed для генератора шума

        % Передача параметров в базовую область для модели Simulink
        assignin('base','to',to);
        assignin('base','Ts',Ts);
        assignin('base','Ns',Ns);
        assignin('base','fc',fc);
        assignin('base','Am',Am);
        assignin('base','R',R);
        assignin('base','mr',mr);
        assignin('base','NP',NP);

        % Запуск модели trenl (FM, вариант 66)
                out = sim('trenl', 'StopTime', num2str(Ts*Ns), ...
                           'ReturnWorkspaceOutputs','on');

        % берём последний отсчёт переданного и принятого сигнала
        u0  = out.simout(end);
        u1v = out.simout1(end);

        uo(k) = (u0  > 0);   % переданный бит
        u1(k) = (u1v > 0);   % принятый бит

    end

    % Интенсивность ошибки передачи сигнала (доля ошибок)
    err_bits   = xor(uo, u1);      % 1 – ошибка, 0 – правильно
    lambda_err = mean(err_bits);   % вероятность / интенсивность ошибки

    Y(j) = lambda_err;

    fprintf('lambda_err (mr=%.3f, NP=%.5f) = %.6f\n', mr, NP, lambda_err);
end

%% Коэффициенты регрессии (линейная модель с взаимодействием)
C  = X*X.';                     % ковариационная матрица
b_ = (C \ (X*Y)).';             % коэффициенты регрессии
disp('Коэффициенты регрессии [b0 b_mr b_NP b_mr*NP] для λ_err:');
disp(b_);

%% Построение поверхности λ_err = f(mr, NP)
mr_vals = mr_min:0.1:mr_max;        % диапазон mr
NP_vals = NP_min:0.01:NP_max;       % диапазон NP
[MM, NN] = meshgrid(mr_vals, NP_vals);

% Нормировка к [-1, +1]
an = 2*(MM - mr_min) / (mr_max - mr_min) - 1;   % нормированный mr
bn = 2*(NN - NP_min) / (NP_max - NP_min) - 1;   % нормированный NP

% Предсказанная реакция по модели
Yc = b_(1) + an.*b_(2) + bn.*b_(3) + an.*bn.*b_(4);

% Визуализация
figure;
plot3(MM, NN, Yc), grid on;
xlabel('mr (коэффициент модуляции)');
ylabel('NP (мощность шума)');
zlabel('\lambda_{err} (интенсивность ошибки передачи)');
title('Интенсивность ошибки передачи сигнала \lambda_{err} = f(mr, NP)');
